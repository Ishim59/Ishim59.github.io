import { readFile } from 'node:fs/promises';
import path from 'node:path';

export function escapeHtml(value) {
  return String(value).replace(
    /[&<>"']/g,
    (character) =>
      ({
        '&': '&amp;',
        '<': '&lt;',
        '>': '&gt;',
        '"': '&quot;',
        "'": '&#39;',
      })[character],
  );
}

/** Loads shared templates once for an entire build. */
export class Layout {
  constructor(templates, site) {
    this.templates = templates;
    this.site = site;
  }

  static async load(root, site) {
    const names = ['header', 'footer', 'search-dialog'];
    const values = await Promise.all(
      names.map((name) => readFile(path.join(root, 'src/templates', `${name}.html`), 'utf8')),
    );
    return new Layout(Object.fromEntries(names.map((name, index) => [name, values[index]])), site);
  }

  render(title, main, { home = false } = {}) {
    return `<!doctype html>
<html lang="ru">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <meta name="theme-color" content="#164e45">
    <meta name="description" content="${escapeHtml(title)} — сайт Бардымской гимназии имени Габдуллы Тукая">
    <title>${escapeHtml(home ? `${this.site.name} ${this.site.subtitle}` : `${title} — Бардымская гимназия`)}</title>
    <link rel="stylesheet" href="/assets/css/site.css">
    <script type="module" src="/assets/js/main.js"></script>
  </head>
  <body>
    <!-- Generated by npm run build. Edit src/ and content/. -->
    <a class="skip" href="#main">Перейти к содержанию</a>
    <div class="utility"><div class="wrap">
      <span>Пермский край · село Барда</span>
      <div><a href="/about/">Сведения об организации ↗</a>
      <button id="vision" aria-pressed="false">◉ <span>Крупный шрифт</span></button></div>
    </div></div>
    ${this.templates.header}
    ${main}
    ${this.templates.footer}
    <div class="demo-banner">${home ? 'Концепция обновления сайта гимназии' : 'Материалы гимназии · информационная версия'}</div>
    ${this.templates['search-dialog']}
  </body>
</html>`;
  }

  article(title, body) {
    const navigation = this.site.navigation
      .map((item) => `<a href="${item.url}">${escapeHtml(item.title)}</a>`)
      .join('\n');
    return this.render(
      title,
      `<main id="main" class="wrap article-layout">
      <aside class="section-nav" aria-label="Разделы гимназии">
        <p class="eyebrow">РАЗДЕЛЫ ГИМНАЗИИ</p>${navigation}
      </aside>
      <article class="article">
        <a class="text-link" href="/">← Главная</a>
        <h1>${escapeHtml(title)}</h1>
        <div class="article-content">${body}</div>
        <a class="button back-home" href="/">Вернуться на главную →</a>
      </article>
    </main>`,
    );
  }
}
